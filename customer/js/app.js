/* ------------------------------------------------------------------ *
 * 8. Search + history (unchanged mechanic from the original app)
 * ------------------------------------------------------------------ */
function setupSearch() {
    const searchInput = document.getElementById("menu-search-input");
    const clearSearchBtn = document.getElementById("clear-search-btn");
    const historyDropdown = document.getElementById("search-history-dropdown");

    searchInput.addEventListener("input", () => {
        state.searchTerm = searchInput.value;
        clearSearchBtn.style.display = searchInput.value.length > 0 ? "block" : "none";
        renderMenuList();
    });

    searchInput.addEventListener("focus", renderSearchHistory);

    document.addEventListener("click", (e) => {
        if (!e.target.closest(".search-section-container")) {
            historyDropdown.classList.add("search-history-hidden");
        }
    });

    searchInput.addEventListener("keypress", (e) => {
        if (e.key === "Enter" && searchInput.value.trim() !== "") {
            saveToSearchHistory(searchInput.value.trim());
            historyDropdown.classList.add("search-history-hidden");
        }
    });

    clearSearchBtn.addEventListener("click", () => {
        searchInput.value = "";
        state.searchTerm = "";
        clearSearchBtn.style.display = "none";
        renderMenuList();
    });

    function saveToSearchHistory(query) {
        searchHistory = searchHistory.filter((item) => item.toLowerCase() !== query.toLowerCase());
        searchHistory.unshift(query);
        if (searchHistory.length > 5) searchHistory.pop();
        renderSearchHistory();
    }

    function renderSearchHistory() {
        const list = document.getElementById("history-items-list");
        if (searchHistory.length === 0) {
            historyDropdown.classList.add("search-history-hidden");
            return;
        }
        list.innerHTML = "";
        searchHistory.forEach((term) => {
            const li = document.createElement("li");
            li.className = "history-item";
            li.innerHTML = `<span>⏳ ${escapeHtml(term)}</span>`;
            li.addEventListener("click", () => {
                searchInput.value = term;
                state.searchTerm = term;
                clearSearchBtn.style.display = "block";
                historyDropdown.classList.add("search-history-hidden");
                renderMenuList();
            });
            list.appendChild(li);
        });
        historyDropdown.classList.remove("search-history-hidden");
    }
}

/* ------------------------------------------------------------------ *
 * 9. Cart engine
 * ------------------------------------------------------------------ */
function setupCartDelegation() {
    // Event delegation: menu items, highlights and offers are all rendered
    // dynamically, so one listener on the page body catches every
    // .add-to-cart-btn click regardless of when it was rendered.
    document.body.addEventListener("click", (e) => {
        const btn = e.target.closest(".add-to-cart-btn");
        if (!btn) return;
        const type = btn.dataset.type;
        const refId = Number(btn.dataset.id);
        const name = btn.dataset.name;
        const price = parseFloat(btn.dataset.price);
        const key = `${type}-${refId}`;

        const existing = state.cart.find((i) => i.key === key);
        if (existing) {
            existing.quantity += 1;
        } else {
            state.cart.push({ key, type, refId, name, price, quantity: 1 });
        }
        updateCartUI();
        showToast(`"${name}" added to basket!`);
    });
}

function updateCartUI() {
    const cartCountEl = document.getElementById("cart-count");
    const container = document.getElementById("cart-items-container");
    const submitBtn = document.getElementById("submit-order-btn");

    const totalItems = state.cart.reduce((acc, i) => acc + i.quantity, 0);
    cartCountEl.innerText = totalItems;

    if (state.cart.length === 0) {
        container.innerHTML = '<p class="empty-cart-msg">Your basket is currently empty. Visit the Menu to add delicious meals!</p>';
        submitBtn.disabled = true;
        updateTotals(0);
        return;
    }

    submitBtn.disabled = false;
    let subtotal = 0;

    container.innerHTML = state.cart
        .map((item) => {
            subtotal += item.price * item.quantity;
            return `
            <div class="cart-item-row">
                <div class="cart-item-info">
                    <h4>${escapeHtml(item.name)}</h4>
                    <span>EGP ${item.price} × ${item.quantity}</span>
                </div>
                <div class="cart-control">
                    <button data-key="${item.key}" data-delta="-1" class="qty-btn">-</button>
                    <span>${item.quantity}</span>
                    <button data-key="${item.key}" data-delta="1" class="qty-btn">+</button>
                </div>
            </div>`;
        })
        .join("");

    updateTotals(subtotal);
}

function changeQuantity(key, delta) {
    const index = state.cart.findIndex((i) => i.key === key);
    if (index === -1) return;

    const item = state.cart[index];
    item.quantity += delta;

    if (item.quantity <= 0) {
        lastRemovedItem = { ...item, originalIndex: index };
        state.cart.splice(index, 1);
        triggerUndoToast(`Removed ${lastRemovedItem.name}`);
    }
    updateCartUI();
}

function triggerUndoToast(message) {
    const undoToast = document.getElementById("undo-notification");
    document.getElementById("undo-msg").innerText = message;
    undoToast.className = "undo-toast-show";
    setTimeout(() => {
        undoToast.className = "undo-toast-hidden";
    }, 6000);
}

function updateTotals(subtotal) {
    const tax = subtotal * 0.14;
    const total = subtotal + tax;
    document.getElementById("subtotal-price").innerText = `EGP ${subtotal.toFixed(0)}`;
    document.getElementById("tax-price").innerText = `EGP ${tax.toFixed(0)}`;
    document.getElementById("total-price").innerText = `EGP ${total.toFixed(0)}`;
    return { subtotal, tax, total };
}

function showToast(message) {
    const toast = document.getElementById("toast-notification");
    toast.innerText = message;
    toast.className = "toast-show";
    setTimeout(() => {
        toast.className = "toast-hidden";
    }, 2500);
}

/* ------------------------------------------------------------------ *
 * 10. Router
 * ------------------------------------------------------------------ */
function setupRouter() {
    const navLinks = document.querySelectorAll(".nav-link, .cart-icon-container");
    const pages = document.querySelectorAll(".page-section");

    navLinks.forEach((link) => {
        link.addEventListener("click", (e) => {
            e.preventDefault();
            const target = link.getAttribute("data-target");
            document.querySelectorAll(".nav-link").forEach((l) => l.classList.remove("active"));
            pages.forEach((p) => p.classList.remove("active"));
            document.getElementById(target).classList.add("active");
            if (link.classList.contains("nav-link")) link.classList.add("active");
        });
    });
}

function goHome() {
    document.querySelector('[data-target="home"]').click();
}

/* ------------------------------------------------------------------ *
 * 11. Table token (QR flow) + order submission
 * ------------------------------------------------------------------ */
function initTableCheck() {
    const params = new URLSearchParams(window.location.search);
    const display = document.getElementById("table-number-display");

    if (params.has("table")) {
        // The token itself is never rendered - it's opaque by design (see
        // 06-QR-CODE-AND-TABLE-FLOW.md) and meaningless to a customer, who
        // already knows which physical table they're sitting at.
        state.tableToken = params.get("table");
        display.innerText = "📱 Table connected — you're ready to order";
        display.classList.remove("table-info-warning");
    } else {
        // Kept intentionally, per 06-QR-CODE-AND-TABLE-FLOW.md section 6:
        // "That's fine to keep for local testing and demos" - a real order
        // attempted with this fallback token is rejected server-side
        // because it won't match any real RestaurantTable.QrToken.
        state.tableToken = "DEV-FALLBACK-TABLE-03";
        display.innerText = APP_CONFIG.DEMO_FALLBACK_ALLOWED
            ? "⚠️ In-App Simulation: Table 03 (no QR code scanned)"
            : "⚠️ No table detected — please scan the QR code on your table to place an order";
        display.classList.add("table-info-warning");
    }
}

async function submitOrder() {
    const submitBtn = document.getElementById("submit-order-btn");
    if (state.cart.length === 0) return;

    const { subtotal, tax, total } = updateTotals(
        state.cart.reduce((acc, i) => acc + i.price * i.quantity, 0)
    );

    const dto = {
        tableToken: state.tableToken,
        items: state.cart.map((i) => ({
            type: i.type,
            id: i.refId,
            quantity: i.quantity,
            notes: null,
        })),
        // Only read by the demo fallback in api.js - a real backend
        // recalculates these from the database and ignores anything else
        // in the request body, per 04-BACKEND-ARCHITECTURE.md section 4.
        __demoSubtotal: subtotal,
        __demoTax: tax,
        __demoTotal: total,
    };

    submitBtn.disabled = true;
    submitBtn.textContent = "Sending...";

    try {
        const response = await OrdersApi.submit(dto);
        const confirmedTotal = response.total ?? total;
        showToast(
            response.demo
                ? `🎉 Demo order #${response.orderId} confirmed — EGP ${confirmedTotal.toFixed(0)}`
                : `🎉 Order #${response.orderId} sent to the kitchen!`
        );
        state.cart = [];
        updateCartUI();
        goHome();
    } catch (err) {
        // The cart is kept (not cleared) so the customer can simply tap again.
        showToast(
            err.name === "ApiUnavailableError"
                ? "Your order was NOT sent - the server can't be reached. Please try again."
                : `Couldn't send the order: ${err.message}`
        );
    } finally {
        submitBtn.disabled = state.cart.length === 0;
        submitBtn.textContent = "Send Order to Kitchen";
    }
}

/* ------------------------------------------------------------------ *
 * Bootstrap
 * ------------------------------------------------------------------ */
window.addEventListener("DOMContentLoaded", () => {
    initTableCheck();
    setupRouter();
    setupSearch();
    setupCartDelegation();

    document.getElementById("undo-action-btn").addEventListener("click", () => {
        if (!lastRemovedItem) return;
        state.cart.splice(lastRemovedItem.originalIndex, 0, {
            key: lastRemovedItem.key,
            type: lastRemovedItem.type,
            refId: lastRemovedItem.refId,
            name: lastRemovedItem.name,
            price: lastRemovedItem.price,
            quantity: 1,
        });
        lastRemovedItem = null;
        updateCartUI();
        document.getElementById("undo-notification").className = "undo-toast-hidden";
        showToast("Action reversed successfully!");
    });

    // Delegated so it keeps working after updateCartUI() replaces the rows.
    document.getElementById("cart-items-container").addEventListener("click", (e) => {
        const btn = e.target.closest(".qty-btn");
        if (!btn) return;
        changeQuantity(btn.dataset.key, Number(btn.dataset.delta));
    });

    document.getElementById("submit-order-btn").addEventListener("click", submitOrder);

    DemoMode.onActivate(showDemoBanner);

    updateHeaderOffsets();
    let resizeTimer;
    window.addEventListener("resize", () => {
        clearTimeout(resizeTimer);
        resizeTimer = setTimeout(updateHeaderOffsets, 150);
    });

    loadInitialData();
});
