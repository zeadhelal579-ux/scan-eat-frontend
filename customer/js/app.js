/*
  FILE: customer/js/app.js
  PURPOSE: The customer app's entire client-side behaviour: the SPA router,
           rendering the menu/categories/offers/home content from data
           instead of hardcoded HTML, the search + category filter engine,
           the cart (add/remove/undo/totals), the table-token flow, and
           submitting the order to the real backend.
  LOGIC:   This is a rewrite of the original Script1.js that keeps every
           piece of behaviour it had (same router, same search-history
           mechanic, same undo flow, same 14% VAT math) but changes *where
           the content comes from*: menu items, categories, offers and the
           two highlight cards are now rendered from data returned by
           customer/js/api.js (MenuApi) instead of being typed directly into
           the HTML - closing the exact gap 05-FRONTEND-ARCHITECTURE.md
           section 2 point 3 describes ("Menu/category/offer data is
           hardcoded in the HTML ... these sections get generated by
           JavaScript from the API response instead"). Because add-to-cart
           buttons are now created dynamically, click handling uses event
           delegation on their container instead of binding one listener per
           button at page-load - the one structural change required to make
           the existing cart logic work against dynamic content, per that
           same document's note that "the cart logic doesn't change, only
           where the list of buttons comes from."
  SECTIONS: 1) state  2) bootstrap/data loading  3) render: home/about
           4) render: categories + filter engine  5) render: menu items
           6) render: highlights (best seller + featured offer)
           7) render: offers page  8) search + history  9) cart engine
           10) router  11) table token + order submission
*/

/* ------------------------------------------------------------------ *
 * 1. Global state
 * ------------------------------------------------------------------ */
const state = {
    categories: [],
    products: [],
    offers: [],
    bestSellerHighlight: null, // single ProductDto
    featuredOffer: null, // single OfferDto
    activeCategory: "all",
    searchTerm: "",
    cart: [], // { key, type: 'product'|'offer', refId, name, price, quantity }
    tableToken: null, // raw QrToken from the URL - never rendered to the DOM
};

let searchHistory = [];
let lastRemovedItem = null;

// Minimal defensive escaping - product/category/offer text ultimately comes
// from admin-entered data once the backend exists, so it's rendered as text,
// never as raw HTML.
function escapeHtml(str) {
    return String(str)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;");
}

// security-test-report.md F6: escapeHtml() alone isn't enough for an
// attribute that's actually a URL (src="${...}") - it stops the attribute
// from being broken out of, but a value like "javascript:alert(1)" is
// still a perfectly well-formed, still-dangerous src. Only accept
// http(s) URLs; anything else (including empty/missing) falls back to a
// harmless value so a broken/malicious imageUrl just shows a broken-image
// icon instead of running script.
function safeImageUrl(url) {
    return /^https?:\/\//i.test(String(url || "")) ? url : "";
}

/* ------------------------------------------------------------------ *
 * 2. Bootstrap / data loading
 * ------------------------------------------------------------------ */
async function loadInitialData() {
    try {
        const [categories, products, offers, bestSellers, info] = await Promise.all([
            MenuApi.getCategories(),
            MenuApi.getProducts(),
            MenuApi.getOffers(),
            MenuApi.getBestSellers({ count: 1 }),
            MenuApi.getRestaurantInfo(),
        ]);

        state.categories = categories;
        state.products = products;
        state.offers = offers;
        state.bestSellerHighlight = bestSellers[0] || null;
        state.featuredOffer = offers.find((o) => o.isFeatured) || null;

        renderHome(info);
        renderCategories();
        renderHighlights();
        renderMenuList();
        renderOffers();
    } catch (err) {
        // Only a genuine ApiHttpError reaches here (network failure is
        // already absorbed into demo data inside MenuApi) - e.g. the
        // backend is up but returned a 500. Show it plainly rather than a
        // silently empty page.
        showFatalMenuError(err);
    }
}

function showFatalMenuError(err) {
    const wrapper = document.getElementById("main-menu-items-wrapper");
    wrapper.innerHTML = `<p class="menu-load-error">Couldn't load the menu (${escapeHtml(
        err.message || "unknown error"
    )}) <button type="button" id="menu-retry-btn" style="display:block;margin:10px auto 0;padding:8px 18px;border:0;border-radius:8px;background:var(--primary-green);color:#fff;font:inherit;cursor:pointer;">Try again</button></p>`;
    // Deliberately NOT the .add-to-cart-btn class: that one is wired to the cart.
    document.getElementById("menu-retry-btn").addEventListener("click", () => {
        wrapper.innerHTML = "";
        loadInitialData();
    });
}

function showDemoBanner(reason) {
    const banner = document.getElementById("demo-mode-banner");
    if (!banner) return;
    banner.textContent = APP_CONFIG.DEMO_BANNER_TEXT;
    banner.hidden = false;
    banner.title = reason || "";
    document.body.classList.add("has-demo-banner");
    updateHeaderOffsets();
}

// Measures the fixed header (and banner, if shown) so CSS can position
// content below them with --header-height / --banner-height instead of a
// hardcoded guess - the header's real height varies with viewport width
// (e.g. the brand name wraps to two lines on very narrow phones), and a
// fixed pixel value previously caused the banner to overlap the header at
// some widths (caught during testing - see README).
function updateHeaderOffsets() {
    const header = document.querySelector(".main-header");
    const banner = document.getElementById("demo-mode-banner");
    document.documentElement.style.setProperty("--header-height", `${header ? header.offsetHeight : 84}px`);
    document.documentElement.style.setProperty(
        "--banner-height",
        banner && !banner.hidden ? `${banner.offsetHeight}px` : "0px"
    );
}

/* ------------------------------------------------------------------ *
 * 3. Home / About
 * ------------------------------------------------------------------ */
function renderHome(info) {
    document.getElementById("about-description").textContent = info.aboutText;
    document.getElementById("establishment-date").textContent =
        info.establishedYear ? `Established in ${info.establishedYear}` : "";
    const certList = document.getElementById("certificates-list");
    certList.innerHTML = "";
    (info.certificates || []).forEach((c) => {
        const li = document.createElement("li");
        li.textContent = c;
        certList.appendChild(li);
    });
}

/* ------------------------------------------------------------------ *
 * 4. Categories + filter engine
 * ------------------------------------------------------------------ */
function renderCategories() {
    const container = document.getElementById("categories-grid-container");
    container.innerHTML = "";

    const allCard = {
        id: "all",
        name: "All Dishes",
        imageUrl: "https://images.unsplash.com/photo-1504674900247-0877df9cc836?w=300",
    };

    [allCard, ...state.categories].forEach((cat) => {
        const card = document.createElement("div");
        card.className = "category-large-card" + (state.activeCategory === cat.id ? " active" : "");
        card.dataset.category = String(cat.id);
        card.innerHTML = `
            <img src="${escapeHtml(safeImageUrl(cat.imageUrl))}" alt="${escapeHtml(cat.name)}">
            <div class="category-overlay"><span>${escapeHtml(cat.name)}</span></div>
        `;
        card.addEventListener("click", () => {
            state.activeCategory = cat.id;
            document
                .querySelectorAll(".category-large-card")
                .forEach((c) => c.classList.remove("active"));
            card.classList.add("active");
            renderMenuList();
            renderHighlights();
        });
        container.appendChild(card);
    });
}

/* ------------------------------------------------------------------ *
 * 5. Menu item list (filtered by category + search)
 * ------------------------------------------------------------------ */
function categoryName(categoryId) {
    const cat = state.categories.find((c) => c.id === categoryId);
    return cat ? cat.name : "";
}

function renderMenuList() {
    const wrapper = document.getElementById("main-menu-items-wrapper");
    const term = state.searchTerm.toLowerCase().trim();

    const filtered = state.products.filter((p) => {
        const matchesCategory = state.activeCategory === "all" || p.categoryId === state.activeCategory;
        const haystack = (p.name + " " + p.description).toLowerCase();
        const matchesSearch = !term || haystack.includes(term);
        return matchesCategory && matchesSearch;
    });

    if (filtered.length === 0) {
        wrapper.innerHTML = `<p class="menu-empty-msg">No dishes match "${escapeHtml(
            state.searchTerm
        )}". Try another search or category.</p>`;
        return;
    }

    wrapper.innerHTML = filtered
        .map(
            (p) => `
        <div class="menu-item">
            <img src="${escapeHtml(safeImageUrl(p.imageUrl))}" alt="${escapeHtml(p.name)}" class="item-img">
            <div class="item-details">
                <div class="item-header">
                    <span class="item-title">${escapeHtml(p.name)}</span>
                    <span class="item-dots"></span>
                    <span class="item-price">EGP ${p.price}</span>
                </div>
                <p class="item-desc">${escapeHtml(p.description)}</p>
                ${
                    p.isAvailable === false
                        ? `<span class="sold-out-badge">Sold Out</span>`
                        : `<button class="add-to-cart-btn" data-type="product" data-id="${p.id}" data-name="${escapeHtml(
                              p.name
                          )}" data-price="${p.price}">Add to Cart</button>`
                }
            </div>
        </div>`
        )
        .join("");
}

/* ------------------------------------------------------------------ *
 * 6. Highlights row (Best Seller + Best Offer)
 * ------------------------------------------------------------------ */
function renderHighlights() {
    const row = document.getElementById("menu-highlights");
    const boxes = [];

    if (state.bestSellerHighlight) {
        const p = state.bestSellerHighlight;
        const visible = state.activeCategory === "all" || p.categoryId === state.activeCategory;
        if (visible) {
            boxes.push(`
                <div class="highlight-horizontal-box">
                    <span class="highlight-tag">🔥 Best Seller</span>
                    <h4>${escapeHtml(p.name)}</h4>
                    <p>${escapeHtml(p.description)}</p>
                    <div class="highlight-footer">
                        <span class="price">EGP ${p.price}</span>
                        <button class="add-to-cart-btn highlight-add-btn" data-type="product" data-id="${p.id}" data-name="${escapeHtml(
                p.name
            )}" data-price="${p.price}">Add</button>
                    </div>
                </div>`);
        }
    }

    if (state.featuredOffer) {
        const o = state.featuredOffer;
        boxes.push(`
            <div class="highlight-horizontal-box">
                <span class="highlight-tag">🎁 Best Offer</span>
                <h4>${escapeHtml(o.title)}</h4>
                <p>${escapeHtml(o.description)}</p>
                <div class="highlight-footer">
                    <span class="price">EGP ${o.newPrice}</span>
                    <button class="add-to-cart-btn highlight-add-btn" data-type="offer" data-id="${o.id}" data-name="${escapeHtml(
            o.title
        )}" data-price="${o.newPrice}">Add</button>
                </div>
            </div>`);
    }

    row.innerHTML = boxes.join("");
    row.style.display = boxes.length ? "flex" : "none";
}

